export function badgeStyle(status) {
  const map = {
    Pending: { color: '#D97706', background: '#FFFBEB', border: '1px solid #FDE68A' },
    'In Progress': { color: '#2563EB', background: '#EFF6FF', border: '1px solid #BFDBFE' },
    Resolved: { color: '#059669', background: '#ECFDF5', border: '1px solid #A7F3D0' },
    Closed: { color: '#64748B', background: '#F1F5F9', border: '1px solid #CBD5E1' },
  }
  return map[status] ?? map.Closed
}
